import { chromium } from 'playwright';
const endpoint = process.env.ELECTRON_CDP || 'http://127.0.0.1:9777';
const browser = await chromium.connectOverCDP(endpoint);
const context = browser.contexts()[0];
const page = context.pages().find(item => item.url().includes('/out/renderer/index.html') || item.url().includes('renderer/index.html'));
if (!page) throw new Error('Renderer not found');
await page.evaluate(() => { localStorage.removeItem('synapse.onboardingComplete'); localStorage.removeItem('synapse.reduceMotion'); });
await page.reload();
await page.waitForTimeout(500);
const boot = await page.getByRole('main', { name: 'Synapse Browser startup' }).count();
await page.waitForTimeout(2400);
const welcome = await page.getByText('Welcome to Synapse Browser', { exact: true }).count();
await page.keyboard.press('Tab');
const focused = await page.evaluate(() => ({ tag: document.activeElement?.tagName, label: document.activeElement?.textContent?.trim() || document.activeElement?.getAttribute('aria-label') }));
await page.getByRole('button', { name: 'Skip Setup' }).click();
await page.waitForTimeout(1800);
const onboardingAfterSkip = await page.getByRole('main', { name: 'Welcome to Synapse Browser' }).count();
const persisted = await page.evaluate(() => localStorage.getItem('synapse.onboardingComplete'));
await page.reload();
await page.waitForTimeout(700);
const onboardingAfterReload = await page.getByRole('main', { name: 'Welcome to Synapse Browser' }).count();
console.log(JSON.stringify({ boot, welcome, focused, onboardingAfterSkip, persisted, onboardingAfterReload, bodyHasTabs: (await page.locator('body').innerText()).includes('TABS:') }, null, 2));
if (!boot || !welcome || onboardingAfterSkip || persisted !== 'true' || onboardingAfterReload) throw new Error('Onboarding persistence or transition acceptance failed');
await browser.close();
